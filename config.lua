-- config.lua
-- 功能开关集中配置
--
-- 原则：
--   1. 所有可开关模块的启用/禁用在此文件统一管理（替代 control.lua 注释开关）
--   2. 每个开关可带参数（如 enabled）
--   3. control.lua 通过 if config.xxx.enabled then require end 加载
--   4. 核心基础设施（utils/chatbot/commands）始终启用，不提供开关
--   5. 改动此文件不影响存档数据（纯加载层配置）

local config = {}

-- =============================================================================
-- 功能模块（modules/）
-- =============================================================================
config.modules = {
    floaty_chat    = { enabled = true },   -- 飘字聊天
    show_inventory = { enabled = true },   -- 显示背包按钮
    autostash      = { enabled = true },   -- 自动整理物品进箱子
    rpg            = { enabled = true },   -- RPG 系统（属性/法术，与地图数值耦合）
    pet_system     = { enabled = true },   -- 宠物系统
}

-- =============================================================================
-- 面板（comfy_panel/）
-- =============================================================================
config.panel = {
    main        = { enabled = true },      -- Comfy 面板主框架
    player_list = { enabled = true },      -- 玩家列表
    admin       = { enabled = true },      -- 管理员
    group       = { enabled = true },      -- 队伍
    poll        = { enabled = true },      -- 投票
    score       = { enabled = true },      -- 分数
    config      = { enabled = true },      -- 面板配置（含底部快捷栏）
}

-- =============================================================================
-- 地图系统（maps/）
-- =============================================================================
config.map = {
    amap_main = { enabled = true },        -- 坦克保卫战主地图（唯一启用地图）
    amap_tank = { enabled = true },        -- 坦克
}

-- =============================================================================
-- 顶栏按钮顺序（必须在各按钮模块之后加载）
-- =============================================================================
config.gui = {
    top_button_order = { enabled = true }, -- mod_gui 大框按钮排序
}

-- =============================================================================
-- 调试
-- =============================================================================
config.debug = {
    dump_env = false,                      -- _DUMP_ENV：转储环境（仅排查用）
}

return config
